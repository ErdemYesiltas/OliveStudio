module.exports = (invoke, listen, stageAssets) => ({
  open: () => invoke('olive:open-scene'),
  save: (name, text) => invoke('olive:save-scene', name, text),
  saveConfig: (token, draft, text) => invoke('olive:save-config', token, draft, text),
  importTranslations: () => invoke('olive:import-translations'),
  exportTranslations: files => invoke('olive:export-translations', files),
  importAssets: async files => invoke('olive:import-assets', await stageAssets(files)),
  network: (action, value) => invoke('olive:network', action, value),
  exportGame: (text, options) => invoke('olive:export-game', text, options),
  exportTargets: () => invoke('olive:export-targets'),
  exportBundles: assets => invoke('olive:export-bundles', assets),
  exportSpineFiles: (asset, format) => invoke('olive:export-spine-files', asset, format),
  convertSpineBinary: asset => invoke('olive:convert-spine-binary', asset),
  spineLauncher: action => invoke('olive:spine-launcher', action),
  history: (token, action, value) => invoke('olive:project-history', token, action, value),
  ai: {
    models: (provider, url) => invoke('olive:ai-status', provider, url),
    run: (id, provider, url, request) => invoke('olive:ai-request', id, provider, url, request),
    cancel: id => invoke('olive:ai-cancel', id),
  },
  localHub: {
    available: () => invoke('olive:localhub-available'),
    status: () => invoke('localhub:status'),
    pair: invite => invoke('localhub:pair', invite),
    unpair: () => invoke('localhub:unpair'),
    chat: (id, request) => invoke('localhub:chat', id, request),
    cancel: id => invoke('localhub:cancel', id),
    onDelta: callback => listen('localhub:delta', callback),
    create: request => invoke('localhub:create', request),
    job: id => invoke('localhub:job', id),
    cancelJob: id => invoke('localhub:job-cancel', id),
    preview: id => invoke('localhub:job-preview', id),
    outputs: id => invoke('localhub:job-outputs', id),
    onEvent: callback => listen('localhub:event', callback),
    files: () => invoke('localhub:files'),
    fileContent: id => invoke('localhub:file-content', id),
    uploadFile: (bytes, name) => invoke('localhub:file-upload', bytes, name),
    deleteFile: id => invoke('localhub:file-delete', id),
  },
  recovery: {
    list: () => invoke('olive:recovery-list'),
    write: (id, name, text) => invoke('olive:recovery-write', id, name, text),
    open: id => invoke('olive:recovery-open', id),
    remove: id => invoke('olive:recovery-remove', id),
  },
  hub: {
    list: () => invoke('olive:hub-list'),
    open: id => invoke('olive:hub-open', id),
    remember: token => invoke('olive:hub-remember', token),
    action: (id, action) => invoke('olive:hub-action', id, action),
    example: id => invoke('olive:hub-example', id),
  },
  onCommand: callback => listen('olive:file-command', callback),
});
