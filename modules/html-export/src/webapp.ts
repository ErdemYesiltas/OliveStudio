/**
 * Installable web app (PWA) for the HTML export (Settings → Web app): a manifest, home-screen icons and a service worker
 * that caches every exported file, so the game installs from the browser and plays offline. Shared by editor and export.
 */
export const webAppSection = 'html.webapp';
export interface WebApp {version: 1; enabled: boolean; name: string; shortName: string;
 /** How the installed app opens: fullscreen (no browser UI) or standalone (status bar kept). */
 display: 'fullscreen' | 'standalone';
 /** Browser UI colour, #rrggbb. */
 themeColor: string}
export const defaultWebApp = (projectName: string): WebApp => ({version: 1, enabled: false, name: projectName.trim().slice(0, 45).trim() || 'Game', shortName: projectName.trim().slice(0, 12).trim() || 'Game', display: 'fullscreen', themeColor: '#191d21'});
/** Checks stored web app settings; problems are returned as messages. */
export function parseWebApp(value: unknown, projectName: string): {app: WebApp; errors: string[]} {
 const base = defaultWebApp(projectName), v = (value && typeof value === 'object' ? value : {}) as Partial<WebApp>, errors: string[] = [];
 const name = typeof v.name === 'string' ? v.name.trim() : base.name, shortName = typeof v.shortName === 'string' ? v.shortName.trim() : base.shortName;
 const themeColor = typeof v.themeColor === 'string' ? v.themeColor.toLowerCase() : base.themeColor, display = v.display === 'standalone' ? 'standalone' : 'fullscreen';
 if (!name || name.length > 45) errors.push('Web app name needs 1–45 characters');
 if (!shortName || shortName.length > 12) errors.push('Short name needs 1–12 characters (it shows under the icon)');
 if (!/^#[0-9a-f]{6}$/.test(themeColor)) errors.push('Theme colour must be #rrggbb');
 return {app: {version: 1, enabled: v.enabled === true, name, shortName, display, themeColor}, errors};
}
/** The web app manifest (icons at icons/icon-192.png and icons/icon-512.png). */
export function webManifest(app: WebApp, background: string, orientation: 'any' | 'landscape' | 'portrait' = 'any') {
 return {name: app.name, short_name: app.shortName, start_url: './', scope: './', display: app.display, orientation, background_color: background, theme_color: app.themeColor,
  icons: [192, 512].flatMap(size => [{src: `icons/icon-${size}.png`, sizes: `${size}x${size}`, type: 'image/png', purpose: 'any'}, {src: `icons/maskable-${size}.png`, sizes: `${size}x${size}`, type: 'image/png', purpose: 'maskable'}])};
}
/**
 * A cache-first service worker for these files: installs them under a cache named by their content `version`, removes
 * older caches when it takes over, and answers from the cache (the network is the fallback; navigations fall back to
 * index.html).
 */
export function serviceWorker(files: readonly string[], version: string, isolateScope = false) {
 return `// Generated by OliveStudio: offline cache for this game build.
const PREFIX = ${isolateScope ? "'pixi-game-' + self.registration.scope + '-'" : "'pixi-game-'"};
const CACHE = ${isolateScope ? 'PREFIX + ' + JSON.stringify(version) : JSON.stringify('pixi-game-' + version)};
const FILES = ${JSON.stringify(['./', ...files.map(f => `./${f}`)])};
self.addEventListener('install', event => { event.waitUntil(caches.open(CACHE).then(cache => cache.addAll(FILES)).then(() => self.skipWaiting())); });
self.addEventListener('activate', event => { event.waitUntil(caches.keys().then(keys => Promise.all(keys.filter(k => k.startsWith(PREFIX) && k !== CACHE).map(k => caches.delete(k)))).then(() => self.clients.claim())); });
self.addEventListener('fetch', event => {
  if (event.request.method !== 'GET') return;
  event.respondWith(caches.open(CACHE).then(cache => cache.match(event.request, {ignoreSearch: true}).then(hit => hit || fetch(event.request).catch(() => event.request.mode === 'navigate' ? cache.match('./index.html') : Response.error()))));
});
`;
}
/** Tags the page head gets (the bootstrap registers the service worker when the manifest link is present). */
export const webAppHead = (app: WebApp) => `<link rel="manifest" href="./manifest.webmanifest"><meta name="theme-color" content="${app.themeColor}"><meta name="mobile-web-app-capable" content="yes"><meta name="apple-mobile-web-app-capable" content="yes"><meta name="apple-mobile-web-app-title" content="${app.shortName.replace(/[<>"&]/g, '')}"><link rel="apple-touch-icon" href="./icons/icon-192.png">`;
